@pytest.mark.parametrize(
    "desc,user_message,reply,expected",
    CASES,
    ids=[c[0] for c in CASES],
)
def test_guard(desc, user_message, reply, expected):
    topic_reason = check_topics(reply, user_message, REFERENCE)
    bad_numbers = check_numbers(reply, REFERENCE)
    blocked = bool(topic_reason) or bool(bad_numbers)
    actual = "block" if blocked else "pass"
    assert actual == expected, (
        f"{desc}: متوقع {expected} وطلع {actual} "
        f"(topic={topic_reason}, numbers={bad_numbers})"
    )
