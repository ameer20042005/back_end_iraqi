_NUMBER_RE = re.compile(r"[\d٠-٩][\d٠-٩,\.]*")
_PHONE_RE = re.compile(r"^0\d{9,10}$")

# تحويل الأرقام العربية-الهندية (٠١٢٣) لخانات لاتينية حتى يطابق «٧٥٠٠٠٠»
# سعرَ الكتالوج «750000» بدل ما يُحسب رقماً مختلَقاً — من الطبقة ١
# (app/text_norm.py) حتى يبقى تعريف واحد بالمشروع كله (يغطي الفارسية أيضاً).

# سلاسل أرقام مفصولة بفراغات تُقرأ رقم هاتف واحد (0770 123 4567) — تُدمج قبل
# الفحص حتى لا تنكسر لثلاثة «أرقام مختلَقة».
_SPACED_PHONE_RE = re.compile(r"\b(0\d{2,3})[ \-]?(\d{3})[ \-]?(\d{4})\b")

# سياقات رقمية غير مالية: الرقم اللي يجي قبل إحدى هذي الكلمات مباشرة هو مدة أو
# كمية أو مواصفة، مو سعراً — فلا يُقاس على الكتالوج.
# ملاحظة: النسبة المئوية (%) **ليست** هنا عمداً — «أنطيك 5% خصم» ادّعاء تسعير
# مختلَق مثل أي سعر، واستثناؤها كان يفتح باباً لخصومات ما يملكها الوكيل.
_NON_PRICE_UNITS = (
    "شهر", "شهور", "سنة", "سنه", "سنين", "يوم", "أيام", "ايام", "ساعة", "ساعه",
    "ساعات", "دقيقة", "دقيقه", "أسبوع", "اسبوع", "قطعة", "قطعه", "حبة", "حبه",
    "جيجا", "غيغا", "ميجا", "تيرا", "انج", "إنش", "انش", "بوصة", "واط", "فولت",
)

# مكوّنات العنوان العراقي: الرقم اللي **يسبقه** واحد من هذي الكلمات هو رقم
# عنوان مو سعر («محلة 425 زقاق 17 دار 9»). العناوين تكثر بالضبط بمرحلة تثبيت
# الطلب — نفس المرحلة اللي كان الدرع ينكسر بيها.
_ADDRESS_PREFIXES = (
    "محلة", "محله", "زقاق", "دار", "شارع", "قطعة", "قطعه", "بناية", "عمارة",
    "شقة", "شقه", "طابق", "مجمع", "حي", "قرب", "مقابل",
)
# رقم الطلب/الوصل — معرّف يولّده النظام، مو سعراً.
_REFERENCE_PREFIXES = ("رقم طلبك", "رقم الطلب", "رقم الوصل", "رقم وصلك", "طلبك رقم")

# كلمات العملة: رقم متبوع بيها هو سعر قطعاً، فما ينفع يتذرّع باستثناء العنوان.
_CURRENCY_WORDS = ("دينار", "الف دينار", "دولار", "IQD", "iqd", "USD", "$")

# صيغ التسعير المختصرة الشائعة عراقياً: «750 الف» = 750,000 و«مليون ونص».
# تُوسَّع لرقمها الكامل قبل الفحص، وإلا انكسر الدرع باتجاهين معاً: «750 الف»
# (سعر صحيح) يُحجب لأن «750» مو بالكتالوج، و«900 الف» (مختلَق) يمرّ لأن الدرع
# يتجاهل الأرقام القصيرة أصلاً.
_SCALE_WORDS = {"الف": 1000, "ألف": 1000, "آلاف": 1000, "مليون": 1_000_000, "ملیون": 1_000_000}
_SCALED_NUMBER_RE = re.compile(
    r"(\d[\d,\.]*)\s*(" + "|".join(_SCALE_WORDS) + r")"
)

# أسعار مكتوبة بالحروف بالكامل («بمليون دينار»، «تسعمية الف») — ما بيها خانة
# رقمية واحدة، فدرع الأرقام أعمى تجاهها تماماً. نمسكها كنمط لفظي مستقل.
_SPELLED_PRICE_WORDS = (
    "مليون", "ملیون", "نص مليون", "تسعمية", "تسعمائة", "ثمنمية", "ثمانمائة",
    "سبعمية", "سبعمائة", "ستمية", "ستمائة", "خمسمية", "خمسمائة",
    "اربعمية", "أربعمائة", "تلثمية", "ثلاثمائة", "ميتين", "مئتين",
)


def _expand_scaled_numbers(text: str) -> str:
    """«750 الف» → «750000» حتى يُقاس على الكتالوج كأي سعر."""
    def repl(m):
        raw = m.group(1).replace(",", "").rstrip(".")
        try:
            value = float(raw) * _SCALE_WORDS[m.group(2)]
        except ValueError:
            return m.group(0)
        return str(int(value))
    return _SCALED_NUMBER_RE.sub(repl, text)


# «مليون شكر» و«الف عافية» مجاملات عراقية مو تسعير — والبرومت يطلب من الوكيل
# يكون مجاملاً، فحجبها كان يعاقبه على تنفيذ أمره. الكلمة تُقرأ سعراً فقط إذا
# ما تبعتها كلمة مجاملة.
_COURTESY_AFTER_SCALE = (
    "شكر", "عافية", "عافيه", "صحة", "خير", "مبروك", "سلامة", "سلامه", "تحية",
)


def _spelled_prices(reply: str) -> List[str]:
    """أسعار مكتوبة حروفاً بلا أي خانة رقمية — تُعامل معاملة الرقم المختلَق
    لأن الوكيل ممنوع يسعّر إلا بأرقام الكتالوج حرفياً. تُستثنى المجاملات
    («مليون شكر») لأنها تعبير ودّ مو رقم."""
    found = []
    for word in _SPELLED_PRICE_WORDS:
        for match in re.finditer(re.escape(word), reply):
            tail = reply[match.end():match.end() + 14].lstrip(" ـ")
            if any(tail.startswith(c) for c in _COURTESY_AFTER_SCALE):
                continue
            found.append(word)
            break
    return found


def _strip_separators(num: str) -> str:
    """يزيل فواصل الآلاف (750,000 → 750000) حتى تتطابق مع أرقام الكتالوج
    الخام (بدون تنسيق) رغم اختلاف صيغة الكتابة."""
    return num.replace(",", "")


# كميات مكتوبة لفظاً باللهجة العراقية — تُقرأ مضاعِفاً مشروعاً للسعر.
_QUANTITY_WORDS = {
    "اثنين": 2, "اثنان": 2, "ثنين": 2, "زوج": 2,
    "ثلاث": 3, "ثلاثة": 3, "تلاث": 3, "تلاثة": 3,
    "اربع": 4, "أربع": 4, "اربعة": 4, "أربعة": 4,
    "خمس": 5, "خمسة": 5, "ست": 6, "ستة": 6,
    "سبع": 7, "سبعة": 7, "ثمان": 8, "ثمانية": 8,
    "تسع": 9, "تسعة": 9, "عشر": 10, "عشرة": 10,
}


def _derivable_sums(allowed: set, reply_digits: set, quantities: set, max_terms: int = 4) -> set:
    """مجاميع مشتقة حسابياً من أسعار **مذكورة بنفس الرد**.

    الوكيل مسموح يجمع أسعاراً موثوقة (سماعة 45,000 + حقيبة 25,000 = 70,000)
    أو يضربها بكمية — المجموع مشتق مو مختلَق، وحجبه كان يقطع أي رد فيه مجموع
    طلب متعدد الأصناف.

    القيد الجوهري: لا نشتق إلا من الأسعار اللي ذكرها الرد نفسه حرفياً
    (`reply_digits`)، مو من كل الكتالوج. بدون هذا القيد كان فضاء «المسموح»
    ينتفخ حتى يبلع أسعاراً مخترعة صدفةً (180,000 × 5 = 900,000 يمرّ كأنه
    مجموع شرعي رغم إن الرد ما ذكر الطاولة أصلاً)."""
    prices = sorted({
        int(a) for a in allowed
        if a.isdigit() and len(a) >= 4 and a in reply_digits
    })[:8]
    sums = set()
    for r in range(2, min(max_terms, len(prices)) + 1):
        for combo in combinations(prices, r):
            sums.add(str(sum(combo)))
    # مضاعفات سعر مذكور بالرد (٣ حبات ماوس = 45,000 والرد ذاكر 15,000).
    # الكمية لازم تكون مذكورة بالرد نفسها (`quantities`) مو أي رقم من ٢ لـ١٠:
    # الترخيص المفتوح للمضاعفات كان يجعل مجموعاً خاطئاً يمرّ صدفةً — «45,000
    # + 25,000 = 90,000» غلط، لكن 90,000 = 45,000 × 2 فيُقرأ مضاعفاً شرعياً.
    for p in prices:
        for q in quantities:
            sums.add(str(p * q))
    return sums


def _stated_quantities(reply: str) -> set:
    """الكميات المذكورة صراحةً بالرد — رقماً (٣ حبات) أو لفظاً (ثلاث)."""
    found = {
        int(n) for n in re.findall(r"\b\d{1,2}\b", reply)
        if 2 <= int(n) <= 20
    }
    for word, value in _QUANTITY_WORDS.items():
        if word in reply:
            found.add(value)
    return found


def check_numbers(reply: str, reference_text: str) -> List[str]:
    """يرجع قائمة الأرقام المالية بـ `reply` غير الموجودة حرفياً بـ
    `reference_text` ولا مشتقة منه حسابياً (مجموع/مضاعف أسعار مذكورة).

    يُستثنى من الفحص:
      - أرقام الهاتف العراقية (07xxxxxxxxx) ولو كُتبت بفراغات — بيانات عميل.
      - الأرقام القصيرة بلا فواصل (≤ رقمين) — كمية أو مدة، مو سعراً.
      - أي رقم متبوع مباشرة بوحدة غير مالية (شهر/سنة/جيجا...).

    ويُمسك إضافةً للأرقام الصريحة: الصيغ المختصرة («900 الف») والأسعار
    المكتوبة حروفاً بالكامل («بمليون دينار») — كلاهما كان يعبر الدرع سابقاً.
    """
    reply_n = _expand_scaled_numbers(
        _normalize_digits(_SPACED_PHONE_RE.sub(r"\1\2\3", reply))
    )
    reference_n = _expand_scaled_numbers(_normalize_digits(reference_text))

    allowed = {_strip_separators(n) for n in _NUMBER_RE.findall(reference_n)}
    reply_digits = {_strip_separators(n.rstrip(".,")) for n in _NUMBER_RE.findall(reply_n)}
    allowed |= _derivable_sums(allowed, reply_digits, _stated_quantities(reply_n))

    bad = list(_spelled_prices(reply))
    for match in _NUMBER_RE.finditer(reply_n):
        clean = match.group().rstrip(".,")
        if _PHONE_RE.match(clean):
            continue
        norm = _strip_separators(clean)
        tail = reply_n[match.end():match.end() + 12].lstrip(" ـ")
        # نسبة مئوية: رقم صغير لكنه ادّعاء تسعير (خصم) — يُفحص قبل استثناء
        # الأرقام القصيرة، وإلا مرّ «أنطيك 5% خصم» بلا فحص إطلاقاً.
        if tail.startswith("%") or tail.startswith("بالمية") or tail.startswith("بالمئة"):
            if norm not in allowed:
                bad.append(clean + "%")
            continue
        if norm in allowed:
            continue
        if "," not in clean and "." not in clean and len(clean) <= 2:
            continue
        # الرقم مقترن بوحدة غير مالية؟ (نفحص ما بعده مباشرة بحدود ١٢ حرفاً)
        if any(tail.startswith(u) for u in _NON_PRICE_UNITS):
            continue
        # الرقم مسبوق بكلمة عنوان أو رقم طلب؟ (نفحص ما قبله بحدود ١٤ حرفاً).
        # مشروط بأن يكون رقماً قصيراً (≤٤ خانات، مثل «محلة 425») وغير متبوع
        # بعملة — وإلا صار الاستثناء بنفسه بوابة تهريب: «بشارع 900000 دينار».
        head = reply_n[max(0, match.start() - 14):match.start()].rstrip(" ـ")
        looks_like_address = (
            len(norm) <= 4
            and "," not in clean
            and not any(tail.startswith(c) for c in _CURRENCY_WORDS)
        )
        if looks_like_address and any(
            head.endswith(p) for p in _ADDRESS_PREFIXES + _REFERENCE_PREFIXES
        ):
            continue
        bad.append(clean)
    return bad


