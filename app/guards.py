_CLAUSE_SPLIT_RE = re.compile(r"[،؛,\.!؟?\n]+|\bبس\b|\bلكن\b|\bمگر\b")


def _split_clauses(text: str) -> List[str]:
    return [c.strip() for c in _CLAUSE_SPLIT_RE.split(text) if c.strip()]


def check_topics(reply: str, user_message: str, reference_text: str) -> Optional[str]:
    """يرجع سبب التدخل (str) إذا الرد يتطرق لموضوع حساس (ضمان/تركيب/تقسيط...)
    مو موجود بـ `reference_text` (سياق منتجات RAG المسترجَعة لهذا السؤال)
    وبدون إحالة صريحة ولا نفي صريح. يرجع None إذا الرد آمن.

    الرد يُعتبر آمناً بأي من هذي الحالات:
      - الموضوع مغطّى فعلاً بنص المنتجات المسترجَعة.
      - الرد يحيل ("أتأكدلك") بدل ما يدّعي.
      - الرد ينفي صراحة ("ماعدنا تقسيط") — نفي صادق مو ادّعاء.
      - الوكيل يسأل العميل سؤالاً عن الموضوع (سؤال العنوان قبل تثبيت الطلب).

    ملاحظة: الكتالوج هنا نص RAG ديناميكي (وصف/تاگات منتج فعلي)، مو قائمة
    مواضيع ثابتة — فلو انضاف حقل "ضمان" لوصف منتج بـ products.json، الدرع
    يرخّص موضوع الضمان تلقائياً بدون أي تعديل هنا."""
    reply_words = _word_set(reply)
    user_words = _word_set(user_message)
    catalog_words = _word_set(reference_text)
    # الوكيل مأمور (SALES_SYSTEM_PROMPT) يسأل العميل عن عنوان التوصيل قبل
    # تثبيت الطلب — سؤال عن العنوان مو ادّعاء معلومة عن خدمة الشحن، فما
    # يحتاج يكون مذكوراً بوصف المنتج. نميّزه بعلامة الاستفهام: جملة خبرية
    # ("عندنا توصيل مجاني") تُفحص عادي، بينما سؤال ("وين عنوانك؟") يُستثنى.
    is_question = "؟" in reply or "?" in reply
    order_context = _customer_gave_delivery_context(user_message)
    clauses = _split_clauses(reply)

    for name, kws in TOPIC_GROUPS.items():
        asked = any(k in user_words for k in kws)
        mentioned = any(k in reply_words for k in kws)
        if not (asked or mentioned):
            continue
        # النفي يُقاس على **الجملة اللي ذكرت الموضوع** لا على الرد كله:
        # «ماعدنا تقسيط، بس عدنا ضمان سنتين» كان يمرّ بالكامل لأن النفي وُجد
        # بمكان ما بالرد، فرخّص ادّعاء الضمان بجملة ثانية. النفي مرتبط بموضوعه.
        topic_clauses = [c for c in clauses if any(k in _word_set(c) for k in kws)] or clauses
        denies = any(p in c for c in topic_clauses for p in DENIAL_PHRASES)
        # الإحالة بالعكس تُقاس على الرد كله: «الضمان 12 شهر، بس خليني أتأكدلك»
        # تأجيل يغطي ما قبله — الوكيل يسحب كلامه بنفس النَّفَس، فتجزئتها كانت
        # تقلب أوضح صيغة تحفّظ إلى «هلوسة».
        defers = any(p in reply for p in CONFIRM_PHRASES)
        # الوكيل يسأل، ما يدّعي — أي موضوع، مو التوصيل بس (سؤال عن اللون
        # المطلوب أو طريقة الدفع نفس المنطق تماماً).
        if is_question and mentioned and not asked:
            continue
        # العميل نفسه أعطى عنواناً أو طلب تثبيت الطلب: تأكيد الوكيل
        # («يوصلك للسماوة») إعادةُ كلام العميل، مو ادّعاء خدمة شحن.
        if name == "توصيل" and order_context and not asked:
            continue
        # ختام تسليم الطلب («يوصلك بأقرب وقت») — وعد بالتسليم مو وصف خدمة
        # توصيل، ويصلح ختاماً لأي عملية بيع ناجحة.
        if name == "توصيل" and not asked and any(
            p in reply for p in _DELIVERY_CLOSING_PHRASES
        ):
            continue
        covered = any(k in catalog_words or k in reference_text for k in kws)
        if covered:
            continue
        if defers or denies:
            continue
        return f"'{name}' غير مغطّى بمعلومات المنتج المسترجَعة — منع هلوسة"
    return None
