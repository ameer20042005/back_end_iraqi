"""راوتر نية خفيف قبل حلقة الأدوات (app/tool_loop.py) — انظر next.md §2
"التوصية النهائية": الاعتماد على انضباط الموديل بالتمييز بين "يحتاج أداة"
و"دردشة بحتة" نقطة هشاشة — مرصود فعلياً إنه يستدعي search_products/
get_order_status حتى لرسالة تحية أو سؤال عن اسمه. حل حتمي رخيص (regex
محلي، بلا أي استدعاء موديل) أضمن من محاولة إقناعه ببرومبت أطول أو
few-shot إضافية.

**محافظ عمداً بالاتجاهين**: يصنّف الرسالة "دردشة بحتة" فقط لو طابقت نمط
تحية/شكر/وداع/هوية معروف **و** ما فيها أي رقم (٣ خانات فأكثر — يغطي رقم
هاتف/طلب/سعر بفحص واحد) **و** ما فيها أي كلمة إشارة بيانات (منتج، طلب،
تتبع...). رسالة مختلطة ("هلا، شنو عدكم غسالات؟") تفشل هذا الفحص فتمر
بالمسار العادي (تستدعي الأداة) — الخطأ الآمن هنا هو استدعاء أداة غير
ضروري (مكلف زمناً بس غير مؤذٍ)، لا العكس.

**شبكة الأمان لو أخطأ التصنيف رغم كل هذا**: بالمبيعات، حرّاس app/guards.py
(عبر _apply_number_and_name_guards بـ app/features/sales/router.py) يحجبون
أي اسم/سعر مختلَق تلقائياً لو ماكو استدعاء أداة بنفس الدور — مرجع فارغ
يعني أي رقم/اسم بالرد مختلَق بالتعريف. بالدعم ماكو حارس برمجي معادل
(SUPPORT_SYSTEM_PROMPT وحده يمنع الاختلاق) — سبب إضافي لإبقاء الفحص هنا
صارماً لا لتخفيفه."""

import re

from app.text_norm import normalize

# ثلاث خانات متتالية فأكثر = رقم هاتف/طلب/سعر محتمل — أبداً ماكو برسالة
# تحية/شكر/هوية بحتة. فحص واسع رخيص أفضل من محاولة سرد كل كلمة بيانات
# ممكنة (نفس فكرة normalize() توحيد الأرقام العربية-الهندية للإنجليزية
# قبل هذا الفحص، فيلتقطها بغض النظر عن صيغة الإدخال).
_DIGITS_RE = re.compile(r"\d{3,}")

# كلمات/عبارات إشارة بيانات — وجود أي وحدة يلغي التصنيف كدردشة بغض النظر
# عن أي كلمة تحية معها بنفس الرسالة. تغطي حاجة المبيعات (منتج/سعر) وحاجة
# الدعم (طلب/تتبع) معاً بقائمة وحدة — رسالة لا تكون "دردشة بحتة" بأي ميزة
# لو ذكرت وحدة منها.
_DATA_SIGNAL_HINTS = (
    "سعر", "شكد", "شقد", "بيك", "عدكم", "عندكم", "متوفر", "موجود", "منتج",
    "اريد", "ابي", "احتاج", "احجز", "اشتري", "شراء",
    "لابتوب", "جوال", "موبايل", "غسال", "ثلاج", "مكيف", "تلفزيون", "سماعة",
    "طلب", "طلبي", "طلبتي", "وصل", "التوصيل", "توصيل", "الشحن", "شحن",
    "حالة", "قيد", "ord",
)

_IDENTITY_HINTS = (
    "شنو اسمك", "شنو أسمك", "شو اسمك", "منو انت", "من انت", "مين انت",
    "مين سواك", "منو سواك", "شنو تسوي", "شنو تسوين", "شنو ذكاء", "شنو بوت",
    "انت بوت", "انت روبوت", "شلون تشتغل", "منو صممك", "شنو شركتك",
)
_GREETING_HINTS = (
    "السلام عليكم", "سلام عليكم", "هلا", "هلو", "مرحبا", "صباح الخير",
    "مساء الخير", "شلونك", "شخبارك", "شعليك", "كيفك", "هاي",
)
_THANKS_HINTS = (
    "شكرا", "شكراً", "تسلم", "تسلمين", "يعطيك العافية", "مشكور", "مشكورة",
    "الله يخليك", "تسلملي", "الله يعافيك",
)
_FAREWELL_HINTS = ("باي", "مع السلامة", "الله وياك", "تصبح على خير", "دمتم")

_CHITCHAT_HINTS = _IDENTITY_HINTS + _GREETING_HINTS + _THANKS_HINTS + _FAREWELL_HINTS
_CHITCHAT_HINTS_NORM = tuple(normalize(h) for h in _CHITCHAT_HINTS)
_DATA_SIGNAL_HINTS_NORM = tuple(normalize(h) for h in _DATA_SIGNAL_HINTS)


def is_pure_chitchat(message: str) -> bool:
    """هل هذي رسالة تحية/شكر/وداع/هوية بحتة، بلا أي إشارة تحتاج بيانات
    حقيقية (منتج/طلب/رقم)؟ محافظ عمداً — انظر شرح الملف أعلاه."""
    normalized = normalize(message)
    if not normalized:
        return False
    if _DIGITS_RE.search(normalized):
        return False
    if any(h in normalized for h in _DATA_SIGNAL_HINTS_NORM):
        return False
    return any(h in normalized for h in _CHITCHAT_HINTS_NORM)
