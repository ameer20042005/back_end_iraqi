# -*- coding: utf-8 -*-
"""الطبقة ١ — تطبيع النص العربي قبل أي معالجة (توكنة، بحث، مطابقة، تدريب).

**مصدر الحقيقة الوحيد للتطبيع بالمشروع كله.** أي كود يطبّع نصاً عربياً
يستورد من هنا — ما ينسخ القواعد لنفسه. السبب أن التطبيع لازم يكون *متطابقاً*
بين ثلاثة مواضع، وأي اختلاف بينها يكسر البحث بصمت:

1. نص الزبون الداخل (query) — قبل التوكنة.
2. بيانات الفهرس (كتالوج المنتجات، مصطلحات اللهجة، أسماء المناطق) — عند البناء.
3. بيانات التدريب (fine-tuning) — بنفس الشكل، وإلا الموديل يتعلم توزيعاً
   مختلفاً عن اللي يشوفه بالإنتاج.

القواعد (بالترتيب — الترتيب مهم):
- توحيد الألف: أ إ آ ٱ ٲ ٳ ٵ → ا
- توحيد الواو/الياء بالهمزة: ؤ → و ، ئ → ي ، ى → ي
- ة → ه (اختيار ثابت — المهم الثبات مو الاتجاه)
- حذف التشكيل (الحركات) والتطويل (ــــ) وعلامات التحكم غير المرئية
- الأرقام العربية-الهندية والفارسية → إنجليزية
- تقليص الحروف المكررة: أكثر من حرفين متتاليين → حرفين (هلللللو → هللو)
- تجريد علامات الترقيم (عربية وإنجليزية) → فراغ
- تقليص الفراغات المتعددة

ملاحظة على تقليص التكرار: يُطبَّق على **الحروف فقط**، لا الأرقام. «٠٧٧٧...»
برقم هاتف عراقي لازم تبقى ثلاث سبعات — تقليصها يخرّب أرقام الهواتف.
"""

import re

# ---------------------------------------------------------------------------
# جداول ومحارف
# ---------------------------------------------------------------------------

# التشكيل (U+064B–U+0652) + الألف الخنجرية والعلامات القرآنية + التطويل
_DIACRITICS_RE = re.compile(r"[ً-ْٓ-ٰٕۖ-ۭـ]")

# محارف تحكم غير مرئية: تنسيق ثنائي الاتجاه، مسافة صفرية، ZWJ/ZWNJ
_INVISIBLE_RE = re.compile(r"[​-‏‪-‮⁦-⁩﻿]")

# الأرقام العربية-الهندية (٠-٩) والفارسية (۰-۹) → إنجليزية
_DIGITS_MAP = str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")

# توحيد أشكال الحروف
_LETTERS_MAP = str.maketrans({
    "أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ٲ": "ا", "ٳ": "ا", "ٵ": "ا",
    "ؤ": "و", "ئ": "ي", "ى": "ي",
    "ة": "ه",
    "ک": "ك", "ﻙ": "ك",   # كاف فارسية/أشكال عرض
    "ی": "ي", "ﻱ": "ي",   # ياء فارسية
    "گ": "ك",             # گاف — تُكتب أحياناً بالعراقي («گلي») لكن المقابل «ك»
})

# ترقيم عربي وإنجليزي — يُستبدل بفراغ لا يُحذف، حتى «سعر،اللابتوب» تنفصل كلمتين
_PUNCT_RE = re.compile(
    r"[!\"#$%&'()*+,\-./:;<=>?@\[\\\]^_`{|}~"
    r"،؛؟٪-٭۔‐-‧‰-⁞]"
)

# ثلاثة تكرارات فأكثر لنفس الحرف العربي/اللاتيني → حرفان
_REPEAT_RE = re.compile(r"([ء-يa-zA-Z])\1{2,}")

_SPACES_RE = re.compile(r"\s+")


# ---------------------------------------------------------------------------
# اللبنات — كل واحدة قابلة للاستعمال منفصلة
# ---------------------------------------------------------------------------


def normalize_digits(text: str) -> str:
    """الأرقام العربية-الهندية والفارسية → إنجليزية. آمنة على بقية النص."""
    return text.translate(_DIGITS_MAP)


def strip_diacritics(text: str) -> str:
    """حذف التشكيل والتطويل ومحارف التحكم غير المرئية."""
    return _INVISIBLE_RE.sub("", _DIACRITICS_RE.sub("", text))


def unify_letters(text: str) -> str:
    """توحيد الألف والياء والتاء المربوطة وأشكال الحروف الفارسية."""
    return text.translate(_LETTERS_MAP)


def reduce_repeats(text: str) -> str:
    """تقليص تكرار الحرف الواحد لحرفين («هلللللو» → «هللو»).

    الأرقام مستثناة عمداً — «٠٧٧٧١٢٣٤٥٦٧» رقم هاتف صحيح، وتقليص السبعات
    يخرّبه. القيد أن مدّ الحرف بالعربية للتعبير («هلااااا») ما يغيّر المعنى،
    بينما تكرار الرقم يغيّر القيمة."""
    return _REPEAT_RE.sub(r"\1\1", text)


def strip_punctuation(text: str) -> str:
    """استبدال الترقيم بفراغ (لا حذفه) حتى لا تلتصق الكلمات المتجاورة."""
    return _PUNCT_RE.sub(" ", text)


# ---------------------------------------------------------------------------
# الدالة الموحّدة
# ---------------------------------------------------------------------------


def normalize(text: str, *, keep_punctuation: bool = False) -> str:
    """التطبيع الكامل — هذي الدالة اللي تُستدعى قبل التوكنة وقبل بناء الفهرس.

    `keep_punctuation=True` تُبقي الترقيم (مفيدة لتطبيع نص معروض للمستخدم أو
    لنص تدريب نريد قراءته طبيعياً)، والباقي من القواعد يُطبَّق كما هو.
    """
    if not text:
        return ""

    text = strip_diacritics(text)
    text = unify_letters(text)
    text = normalize_digits(text)
    text = reduce_repeats(text)
    if not keep_punctuation:
        text = strip_punctuation(text)
    text = _SPACES_RE.sub(" ", text)
    return text.strip().lower()
