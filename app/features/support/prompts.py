# ---------------------------------------------------------------------------
# فهم سؤال الموظف — البديل عن جداول الكلمات المحذوفة بـrouter.py
# ---------------------------------------------------------------------------
#
# البرومبت **ما يذكر أي حالة أو اسم مندوب**: القوائم تُحقن وقت التشغيل من
# البيانات الحية، ويفرضها guided_json كـenum (انظر router.py::
# build_support_query_schema). كتابتها هنا يعيد نفس مشكلة _STATUS_SYNONYMS
# المحذوفة — قائمة بالكود تتقادم أول ما تتغير البيانات.

_SUPPORT_QUERY_PROMPT = """أنت محلّل استعلامات. مهمتك الوحيدة: تحويل سؤال موظف عن دفتر الطلبات إلى حقول. لا تكتب أي كلام آخر.

# intent — نوع الاستعلام
- "by_status"      — يسأل عن طلبات بحالة معينة ("شنو الطلبات قيد التوصيل؟"، "المكتملة").
- "latest"         — يريد **الأحدث فقط** ("اخر طلب"، "احدث طلب مسلّم").
- "by_transporter" — يسأل عن طلبات مندوب توصيل بالاسم.
- "by_date_range"  — يحدد فترة زمنية ("من الشهر الماضي"، "بين تاريخ وتاريخ").
- "list_all"       — كل الطلبات بلا تقييد ("كل الطلبات"، "كم طلب عدنا؟").
- "contacts"       — يطلب أرقام هواتف الزبائن.
- "none"           — أي شي ثاني: سؤال عام، دردشة، سؤال عن طلب واحد برقمه.

# status — حالة الطلب
اختر من القائمة المعطاة لك أدناه **حرفياً**، أو "none" إذا ما ذكر حالة.
الموظف يستعمل كلاماً دارجاً ("مكتمله"، "بالطريق"، "مشحونه"، "منجزه"، "واصلت") — طابقه على أقرب حالة **موجودة بالقائمة**. إذا ماكو حالة تناسب، اكتب "none" ولا تخترع.

# transporter — اسم المندوب
من القائمة المعطاة حرفياً، أو "none".

# wants_count — هل يريد **رقماً** لا قائمة؟
true إذا سأل "كم" / "شكد" / "عدد" / "چم" أو أي صيغة تطلب عدداً. false إذا يريد القائمة نفسها.

# relative_range — الفترة النسبية
"today" / "yesterday" / "last_week" / "last_month" / "none".
⚠️ **لا تحسب تواريخ ولا تكتبها** — اختر المفتاح بس، والخادم يحسب. والتواريخ المكتوبة صراحة بالرسالة (2026-08-01) يستخرجها الخادم بنفسه، فاكتب "none" لها.

# المتابعات
إذا كانت الرسالة الأخيرة ناقصة المعنى لوحدها ("اعطني هذه الطلبات"، "وهاي؟")، استعمل رسائل الموظف السابقة لتحديد الحالة المقصودة.

# اللغة
السؤال قد يجي بالعربية الفصحى أو العراقية أو الكردية السورانية أو الإنكليزية — كلها تُحوَّل لنفس الحقول."""


def build_support_query_prompt(
    message: str,
    history: Optional[List[Message]],
    statuses: List[str],
    transporters: List[str],
) -> List[Message]:
    """يبني رسائل استخراج استعلام الموظف — تُستدعى بمخطط مقيَّد مبني من
    نفس القائمتين (router.py::build_support_query_schema).

    القوائم تُحقن بالبرومبت **وبالمخطط** معاً: المخطط يمنع النموذج فيزيائياً
    من قيمة خارجها، والبرومبت يخليه يعرف شنو المتاح فيختار بذكاء بدل ما
    يضطر المولّد المقيَّد يجبره على أول قيمة."""
    lines = ["الحالات الموجودة فعلاً بالنظام: " + ("، ".join(statuses) if statuses else "(ماكو)")]
    if transporters:
        lines.append("أسماء المندوبين: " + "، ".join(transporters))

    # آخر أربع رسائل من الموظف تكفي للمتابعات — أكثر منها يضخّم البرومبت
    # بلا فائدة (المتابعة دائماً قريبة من سياقها).
    if history:
        past = [m.get("content", "") for m in history if m.get("role") == "user"][-4:]
        if past:
            lines.append(
                "رسائل الموظف السابقة (الأقدم أولاً):\n"
                + "\n".join(f"- {p}" for p in past)
            )

    lines.append("سؤال الموظف الحالي:\n" + message)

    return [
        {"role": "system", "content": _SUPPORT_QUERY_PROMPT},
        {"role": "user", "content": "\n\n".join(lines)},
    ]
