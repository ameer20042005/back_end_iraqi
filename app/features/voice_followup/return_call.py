# خريطة القرار ← (الإجراء، الحالة الجديدة) — منقولة من
# CallDecisionProcessorImpl بخدمة الـ AI Call، قسم حالة "راجع" ونتائجها.
#
# المبدأ الحاكم بالدليل: **لا يُوثق بالإجراء اللي يقترحه النموذج** — يُحسب
# من هذي الخريطة. None بمكان الحالة تعني "لا تغيّر حالة الشحنة": قرار
# NO_ACTION_NEEDED يسجّل ملاحظة بس (رقم غلط/شخص غير مخوّل)، ما يحرّك
# الشحنة بأي اتجاه.
RETURN_DECISION_MAP = {
    "CONFIRMED_RETURN": ("RETURN_APPROVED", "APPROVAL_RETURN"),
    "CUSTOMER_WILL_RECEIVE": ("TREATED", "TRY_AGAIN"),
    "CUSTOMER_READY_NOW": ("TREATED", "TRY_AGAIN"),
    "CONFIRMED_POSTPONED": ("APPROVAL_POSTPONED", "APPROVAL_POSTPONED"),
    "NO_ACTION_NEEDED": ("NO_ACTION_NEEDED", None),
}


def resolve_return_decision(reason_key: str, accepted: bool) -> Optional[str]:
    """يحوّل (سبب الرجوع + هل قبل الزبون الحل المعروض؟) لقرار نهائي.

    هذي قواعد العمل كلها بسطور معدودة، وكل فرع يطابق سطراً بالدليل:
    ما طلبها وقبل ← راح يستلمها؛ ماكو وقت وقبل ← تأجيل؛ مشكلة مندوب وقبل ←
    إعادة إرسال؛ متردد وقبل ← توصيل اليوم؛ رافض وقال نعم ← راجع نهائي؛
    وأي رفض للحل ← راجع نهائي.

    ترجع None بحالة وحدة: رافض الاستلام لكنه رفض إثبات الرجوع كذلك — تضارب
    ما ينحسم، والدليل يوجب عندها إعادة السؤال لا التخمين.
    """
    if reason_key == "refused":
        return "CONFIRMED_RETURN" if accepted else None
    if not accepted:
        return "CONFIRMED_RETURN"
    return {
        "no_order": "CUSTOMER_WILL_RECEIVE",
        "no_time": "CONFIRMED_POSTPONED",
        "agent_issue": "CUSTOMER_WILL_RECEIVE",
        "hesitant": "CUSTOMER_READY_NOW",
    }[reason_key]


