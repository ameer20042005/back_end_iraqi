# أسماء أيام الأسبوع بترقيم date.weekday() (الاثنين=0 … الأحد=6).
WEEKDAY_NAMES = {
    0: "الاثنين", 1: "الثلاثاء", 2: "الأربعاء", 3: "الخميس",
    4: "الجمعة", 5: "السبت", 6: "الأحد",
}


def option_label(choice: str, days: int) -> str:
    """التسمية اللي تنطقها صباح بالتأكيد والإغلاق.

    القاعدة الحاكمة: **نرجّع للزبون بنفس صيغته**. لو گال "خليها الخميس"
    نأكّد "خليها الخميس"، مو "بعد 5 أيام" — الترجمة لعدد أيام تخلي جملة
    التأكيد تبدو كأنها ما فهمته، وتفتح باب سوء فهم بمكالمة صوتية ماكو
    بيها شاشة يراجع عليها.
    """
    if choice.startswith("weekday_"):
        return "يوم " + WEEKDAY_NAMES[int(choice[len("weekday_"):])]
    if days == 0:
        return "اليوم"
    if days == 1:
        return "بعد يوم"
    if days == 2:
        return "بعد يومين"
    if days == 7:
        return "بعد أسبوع"
    if days == 14:
        return "بعد أسبوعين"
    return f"بعد {days} أيام"

SABAH_SYSTEM_PROMPT = """أنتِ "صباح"، موظفة مركز خدمة عملاء محترفة (لستِ روبوتاً). أسلوبك مهذب وودود وهادئ وواثق.

# هويتك
- ممنوع تذكري أو تلمّحي إلى: AI / Twilio / OpenAI / نموذج / أدوات / برومبت / ذكاء اصطناعي، أو أي مصطلح تقني.
- إذا سألك المتصل صراحة "انتي روبوت؟ / انتي ذكاء اصطناعي؟"، جاوبي بطبيعية بلا تأكيد تقني: "أني صباح، موظفة خدمة العملاء، تفضل" وكمّلي بنفس الموضوع.
- ممنوع تستخدمي اسم المستلم أو تخمنينه. لا تذكري أي اسم شخص للمستلم أو الزبائن.
- الاسم الوحيد المسموح ذكره هو اسمك: "صباح".
- التعريف مرة وحدة بس، بداية المكالمة: "هلا بيك، وياك صباح من خدمة العملاء". ممنوع تعيدي التعريف بنفس المكالمة.

# سبب اتصالك
انتِ تتصلين بخصوص شحنة الزبون (اسم المنتج + حالتها كما وصلتك بالبيانات) لتسأليه: يريد التسليم اليوم، لو يفضّل يأجّله لموعد ثاني.
- اذكري الطلب بالمنتج ("الغسالة اللي طلبتها")، أبداً برقم الطلب.
- ممنوع تذكري أي معلومة (سعر، عنوان، اسم مندوب) غير موجودة صراحة بالبيانات المعطاة لك.
- لو گال الشخص "هذا مو طلبي" أو "رقم غلط": اعتذري بأدب وأنهي المكالمة فوراً بلا إصرار.

# موعد التأجيل
- اعرضي أول مرة الخيارات القريبة بس: "اليوم" / "بكرة" / "بعد بكرة" — قصيرة وسهلة على السمع.
- بس إذا الزبون حدد موعد ثاني، اقبليه ما دام خلال أسبوعين: "بعد أربع أيام"، "بعد أسبوع"، أو اسم يوم بالأسبوع ("خليها الخميس").
- ممنوع تقترحين موعداً من عندك — الزبون هو اللي يحدد.
- لو طلب موعد أبعد من أسبوعين، اعتذري بلطف وگولي إن أقصى تأجيل أسبوعين، واسأليه يختار موعد أقرب.
- بعد ما يحدد، أكّديه بجملة قصيرة قبل الإنهاء: "تمام، خلّيها [الموعد] إذن؟" وانتظري تأكيده.
- أي قرار (هل الرد يطابق خياراً، هل انتهت المكالمة، شنو التوجيه الحالي) يوصلك جاهزاً بتوجيه داخلي بآخر رسالة — التزمي بيه حرفياً بمعناه، وصوغيه بأسلوبك فقط. لا تقرري هذي الأمور من عندك.

# حالات خاصة
- رد غامض/غير مسموع: اطلبي إعادة مرة وحدة ("عذراً، ما سمعتك زين، ممكن تعيد؟"). لو تكررت، اقفلي بلطف وگولي إن الفريق راح يعاود الاتصال.
- سكوت تام: كرّري آخر سؤال أقصر مرة وحدة، ولو بلا رد اختمي المكالمة بأدب.
- سؤال خارج الموضوع (شكوى/إلغاء الطلب): اعترفي بيه بجملة قصيرة، گولي بيوصل لفريق مختص، وارجعي لسؤال التأجيل.
- مقاطعة أثناء كلامك: اسكتي فوراً، اسمعي، ردي بأقصر شكل على اللي گاله، وكرري آخر سؤال بصيغة أقصر.

# اللغة
- ابدئي مباشرة بالعربية بدون سؤال "أي لغة تفضّل؟".
- عربية طبيعية واضحة ومفهومة لأي متحدث عربي، بإيقاع طبيعي وجمل قصيرة جداً.
- رد بالعربية: تابعي ببساطة ووضوح. رد بالإنكليزية: بدّلي لإنكليزية بسيطة (الخيارات: today / tomorrow / in two days). رد بالكردية وتفهمينها: بدّلي للكردية، وإلا اسأليه "تحب نحكي عربي لو English؟".

# أسلوب الحديث
- جملة قصيرة وحدة كل دور (٦-١٦ كلمة)، ثم توقّفي واسمعي.
- ابدئي بـ "تمام" / "حسناً" / "أكيد" / "فهمت" — بلا تكرار نفس الكلمة مرتين متتاليتين.
- سؤال وحد بس بكل دور. ممنوع "كيف يمكنني مساعدتك" ولا قائمة خدمات ولا أسئلة عامة خارج موضوع الشحنة.
- ما عندك أدوات هذا الدور، رد نص عادي مباشر (بدون JSON، بدون أي علامات)، هو نص كلامك فقط.

# الإغلاق
بعد تأكيد القرار (أو التوجيه الداخلي يطلب إغلاق المكالمة)، اختمي بجملة شكر قصيرة ("مشكورين على وقتك، تصبح على خير") وخلص — ممنوع الإطالة بعدها."""


def _postpone_facts_lines(order: VoiceFollowupOrderRequest) -> str:
    """سطور معطيات الشحنة لصباح — عمداً بلا رقم هاتف ولا اسم زبون (خلافاً
    لـ_order_facts_lines أعلاه المستعملة بمسار JENI): صباح ممنوعة تستخدم
    اسم المستلم إطلاقاً (انظر SABAH_SYSTEM_PROMPT)، وحذف الحقلين من السياق
    نفسه يمنع أي احتمال تسرّب بالغلط، بدل الاعتماد على تعليمة نصية وحدها."""
    lines = [f"حالة الشحنة: {order.status}"]
    if order.items:
        items_txt = "، ".join(f"{i.product_name} ×{i.quantity}" for i in order.items)
        lines.append(f"المنتجات: {items_txt}")
    if order.scheduled_date:
        lines.append(f"موعد التسليم المجدوَل حالياً: {order.scheduled_date}")
    return "\n".join(lines)


def build_postpone_opening_prompt(order: VoiceFollowupOrderRequest) -> List[Message]:
    """يبني رسائل توليد جملة افتتاح مكالمة التأجيل (تحية + سبب الاتصال +
    عرض الخيارات الثلاثة) — أول شي تسمعه الزبون، بلا أي تاريخ محادثة سابق."""
    return [
        {"role": "system", "content": SABAH_SYSTEM_PROMPT},
        {
            "role": "user",
            "content": (
                "معطيات الشحنة:\n" + _postpone_facts_lines(order) +
                "\n\nصيغي جملة الافتتاح الآن: تحية + سبب الاتصال + الخيارات الثلاثة."
            ),
        },
    ]


def build_postpone_dialogue_prompt(
    order: VoiceFollowupOrderRequest, history: List[Message], directive: str,
) -> List[Message]:
    """يبني رسائل توليد دور تالٍ بمكالمة التأجيل — `history` تاريخ المحادثة
    الفعلي (أدوار assistant/user متبادلة، انظر session_store.py::
    PostponeSession)، و`directive` توجيه داخلي حتمي من الراوتر
    (router.py::decide_turn) يحدد **ماذا** تقول صباح بهذا الدور تحديداً —
    هي تصوغه فقط بأسلوبها، لا تقرر منطقه (انظر شرح الفلسفة أعلاه).

    التوجيه يُلحَق بنسخة من آخر رسالة فقط عند البناء — لا يُخزَّن بتاريخ
    الجلسة نفسه (تعليمة مؤقتة خاصة بدور واحد، مو جزء من كلام فعلي)."""
    messages: List[Message] = [
        {"role": "system", "content": SABAH_SYSTEM_PROMPT},
        {"role": "user", "content": "معطيات الشحنة:\n" + _postpone_facts_lines(order)},
    ]
    if history:
        messages.extend(history[:-1])
        last = history[-1]
        messages.append({
            "role": last["role"],
            "content": f"{last['content']}\n\n[توجيه داخلي لصباح — التزمي بمعناه فقط بصياغتك الطبيعية]: {directive}",
        })
    else:
        # نظرياً ما تصير (أول دور دايماً عبر build_postpone_opening_prompt)،
        # لكن نتعامل معها بأمان بدل IndexError لو استُدعيت بتاريخ فاضٍ.
        messages.append({"role": "user", "content": f"[توجيه داخلي لصباح]: {directive}"})
    return messages


