# أسماء أيام الأسبوع بترقيم date.weekday() (الاثنين=0 … الأحد=6).
WEEKDAY_NAMES = {
    0: "الاثنين", 1: "الثلاثاء", 2: "الأربعاء", 3: "الخميس",
    4: "الجمعة", 5: "السبت", 6: "الأحد",
}


def option_label(choice: str, days: int) -> str:
    """التسمية اللي تنطقها صباح بالتأكيد والإغلاق.

    القاعدة الحاكمة: **نرجّع للزبون بنفس صيغته**. لو گال "خليها الخميس"
    نأكّد "خليها الخميس"، مو "بعد 5 أيام" — الترجمة لعدد أيام تخلي جملة
    التأكيد تبدو كأنها ما فهمته، وتفتح باب سوء فهم بمكالمة صوتية ماكو
    بيها شاشة يراجع عليها.
    """
    if choice.startswith("weekday_"):
        return "يوم " + WEEKDAY_NAMES[int(choice[len("weekday_"):])]
    if days == 0:
        return "اليوم"
    # "باجر"/"بعد باجر" لا "بعد يوم"/"بعد يومين": هذي **نفس** الكلمات اللي
    # تعرضها صباح بالسؤال (انظر قسم "موعد التأجيل" بـSABAH_SYSTEM_PROMPT)،
    # فتأكيدها بصيغة ثانية يخلي الزبون يشك إنها فهمته غلط بمكالمة صوتية
    # ماكو بيها شاشة يراجع عليها — وهذا بالضبط اللي تحذّر منه الـdocstring.
    if days == 1:
        return "باجر"
    if days == 2:
        return "بعد باجر"
    if days == 7:
        return "بعد أسبوع"
    if days == 14:
        return "بعد أسبوعين"
    return f"بعد {days} أيام"

