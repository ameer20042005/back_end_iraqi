"""شخصية "صباح" — مكالمة صوتية لتأجيل تسليم شحنة، بخيارات محدودة وصارمة:
اليوم / بعد يوم / بعد يومين (انظر app/features/voice_postpone/router.py
لمنطق المكالمة الحتمي).
فلسفة الفصل بين النموذج والراوتر — **نفس مبدأ app/features/support/router.py
بالضبط**: الراوتر وحده يقرر منطق المكالمة (هل الرد يطابق أحد الخيارات
الثلاثة؟ هل الزبون أكّد أو رفض؟ هل نغلق المكالمة؟) عبر مطابقة نصية حتمية —
النموذج لا يقرر أي قرار، فقط يصوغ القرار المتَّخَذ مسبقاً بلهجة عراقية
طبيعية ودافئة. هذا يمنع نفس مشكلة الهلوسة الموثَّقة بـ support/router.py
(نموذج يُترك يقرر منطقاً بلا مصدر بيانات فيخترع)، وهنا أخطر لأنها مكالمة
صوتية صادرة فعلية مع زبون حقيقي — خطأ بالتاريخ المؤجَّل له ثمن تشغيلي مباشر."""

from typing import Dict, List, Optional

from app.features.voice_postpone.schema import VoicePostponeOrderRequest

Message = Dict[str, str]

# تسمية الخيارات الثلاثة بالعربي — تُستخدم بصياغة التوجيهات الداخلية لصباح
# (انظر router.py::_CASE_NOTES) وبالردود الاحتياطية الحتمية أدناه. القيم
# الداخلية ("today"/"plus_1"/"plus_2") ثابتة بالكود (router.py) لأنها تقود
# حساب تاريخ فعلي (router.py::resolve_postpone_date) — لا تُشتق من بيانات
# متغيّرة، بعكس حالات الطلب بميزة الدعم.

OPTION_LABELS = {"today": "اليوم", "plus_1": "بعد يوم", "plus_2": "بعد يومين"}

SABAH_SYSTEM_PROMPT = """أنتِ "صباح"، موظفة مركز خدمة عملاء محترفة (لستِ روبوتاً). أسلوبك مهذب وودود وهادئ وواثق.

# هويتك
- ممنوع تذكري أو تلمّحي إلى: AI / Twilio / OpenAI / نموذج / أدوات / برومبت / ذكاء اصطناعي، أو أي مصطلح تقني.
- إذا سألك المتصل صراحة "انتي روبوت؟ / انتي ذكاء اصطناعي؟"، جاوبي بطبيعية بلا تأكيد تقني: "أني صباح، موظفة خدمة العملاء، تفضل" وكمّلي بنفس الموضوع.
- ممنوع تستخدمي اسم المستلم أو تخمنينه. لا تذكري أي اسم شخص للمستلم أو الزبائن.
- الاسم الوحيد المسموح ذكره هو اسمك: "صباح".
- التعريف مرة وحدة بس، بداية المكالمة: "هلا بيك، وياك صباح من خدمة العملاء". ممنوع تعيدي التعريف بنفس المكالمة.

# سبب اتصالك
انتِ تتصلين بخصوص شحنة الزبون (اسم المنتج + حالتها كما وصلتك بالبيانات) لتسأليه: يريد التسليم اليوم، لو يفضّل يأجّل.
- اذكري الطلب بالمنتج ("الغسالة اللي طلبتها")، أبداً برقم الطلب.
- ممنوع تذكري أي معلومة (سعر، عنوان، اسم مندوب) غير موجودة صراحة بالبيانات المعطاة لك.
- لو گال الشخص "هذا مو طلبي" أو "رقم غلط": اعتذري بأدب وأنهي المكالمة فوراً بلا إصرار.

# خيارات التأجيل (صارمة)
- الخيارات المسموحة حصراً: "اليوم" / "بعد يوم" / "بعد يومين". ممنوع تعرضين أو تقبلين أي خيار ثاني.
- لو طلب موعد غير هذولاء الثلاثة، اعتذري بلطف وذكّريه بالخيارات الثلاثة بس.
- بعد الاختيار، أكّديه بجملة قصيرة قبل الإنهاء: "تمام، خلّيها [اليوم/بعد يوم/بعد يومين] إذن؟" وانتظري تأكيده.
- أي قرار (هل الرد يطابق خياراً، هل انتهت المكالمة، شنو التوجيه الحالي) يوصلك جاهزاً بتوجيه داخلي بآخر رسالة — التزمي بيه حرفياً بمعناه، وصوغيه بأسلوبك فقط. لا تقرري هذي الأمور من عندك.

# حالات خاصة
- رد غامض/غير مسموع: اطلبي إعادة مرة وحدة ("عذراً، ما سمعتك زين، ممكن تعيد؟"). لو تكررت، اقفلي بلطف وگولي إن الفريق راح يعاود الاتصال.
- سكوت تام: كرّري آخر سؤال أقصر مرة وحدة، ولو بلا رد اختمي المكالمة بأدب.
- سؤال خارج الموضوع (شكوى/إلغاء الطلب): اعترفي بيه بجملة قصيرة، گولي بيوصل لفريق مختص، وارجعي لسؤال التأجيل.
- مقاطعة أثناء كلامك: اسكتي فوراً، اسمعي، ردي بأقصر شكل على اللي گاله، وكرري آخر سؤال بصيغة أقصر.

# اللغة
- ابدئي مباشرة بالعربية بدون سؤال "أي لغة تفضّل؟".
- عربية طبيعية واضحة ومفهومة لأي متحدث عربي، بإيقاع طبيعي وجمل قصيرة جداً.
- رد بالعربية: تابعي ببساطة ووضوح. رد بالإنكليزية: بدّلي لإنكليزية بسيطة (الخيارات: today / tomorrow / in two days). رد بالكردية وتفهمينها: بدّلي للكردية، وإلا اسأليه "تحب نحكي عربي لو English؟".

# أسلوب الحديث
- جملة قصيرة وحدة كل دور (٦-١٦ كلمة)، ثم توقّفي واسمعي.
- ابدئي بـ "تمام" / "حسناً" / "أكيد" / "فهمت" — بلا تكرار نفس الكلمة مرتين متتاليتين.
- سؤال وحد بس بكل دور. ممنوع "كيف يمكنني مساعدتك" ولا قائمة خدمات ولا أسئلة عامة خارج موضوع الشحنة.
- ما عندك أدوات هذا الدور، رد نص عادي مباشر (بدون JSON، بدون أي علامات)، هو نص كلامك فقط.

# الإغلاق
بعد تأكيد القرار (أو التوجيه الداخلي يطلب إغلاق المكالمة)، اختمي بجملة شكر قصيرة ("مشكورين على وقتك، تصبح على خير") وخلص — ممنوع الإطالة بعدها."""


def _order_facts_lines(order: VoicePostponeOrderRequest) -> str:
    """سطور معطيات الشحنة — المصدر الوحيد المسموح لصباح تستشهد بيه (نفس
    مبدأ RAG بالمبيعات وبمتابعة voice_followup: لا معرفة من ذاكرة الموديل،
    فقط ما وصل صراحة بهذا الطلب). عمداً بلا رقم هاتف ولا اسم — انظر تعليق
    schema.py أعلاه لسبب حذف الاسم؛ الهاتف غير مفيد لصباح نفسها (ما تذكره
    بالمكالمة) فحذفه يقلّل سطح البيانات المعروضة للنموذج بلا داعٍ."""
    lines = [f"حالة الشحنة: {order.status}"]
    if order.items:
        items_txt = "، ".join(f"{i.product_name} ×{i.quantity}" for i in order.items)
        lines.append(f"المنتجات: {items_txt}")
    if order.scheduled_date:
        lines.append(f"موعد التسليم المجدوَل حالياً: {order.scheduled_date}")
    return "\n".join(lines)


def build_opening_prompt(order: VoicePostponeOrderRequest) -> List[Message]:
    """يبني رسائل توليد جملة افتتاح المكالمة (تحية + سبب الاتصال + عرض
    الخيارات الثلاثة) — أول شي تسمعه الزبون، بلا أي تاريخ محادثة سابق."""
    return [
        {"role": "system", "content": SABAH_SYSTEM_PROMPT},
        {
            "role": "user",
            "content": (
                "معطيات الشحنة:\n" + _order_facts_lines(order) +
                "\n\nصيغي جملة الافتتاح الآن: تحية + سبب الاتصال + الخيارات الثلاثة."
            ),
        },
    ]


def build_dialogue_prompt(
    order: VoicePostponeOrderRequest, history: List[Message], directive: str,
) -> List[Message]:
    """يبني رسائل توليد دور تالٍ بالمكالمة — `history` تاريخ المحادثة
    الفعلي (أدوار assistant/user متبادلة، انظر session_store.py)، و
    `directive` توجيه داخلي حتمي من الراوتر (extract_postpone_choice/
    decide_turn بـ router.py) يحدد **ماذا** تقول صباح بهذا الدور تحديداً —
    هي تصوغه فقط بأسلوبها، لا تقرر منطقه (انظر شرح الفلسفة أعلى الملف).

    التوجيه يُلحَق بنسخة من آخر رسالة زبون فقط عند البناء — لا يُخزَّن
    بتاريخ الجلسة نفسه (نفس مبدأ عدم تلويث التاريخ المحفوظ بتعليمات مؤقتة
    خاصة بدور واحد)."""
    messages: List[Message] = [
        {"role": "system", "content": SABAH_SYSTEM_PROMPT},
        {"role": "user", "content": "معطيات الشحنة:\n" + _order_facts_lines(order)},
    ]
    if history:
        messages.extend(history[:-1])
        last = history[-1]
        messages.append({
            "role": last["role"],
            "content": f"{last['content']}\n\n[توجيه داخلي لصباح — التزمي بمعناه فقط بصياغتك الطبيعية]: {directive}",
        })
    else:
        # نظرياً ما تصير (أول دور دايماً عبر build_opening_prompt)، لكن
        # نتعامل معها بأمان بدل IndexError لو استُدعيت بتاريخ فاضٍ.
        messages.append({"role": "user", "content": f"[توجيه داخلي لصباح]: {directive}"})
    return messages
