# -*- coding: utf-8 -*-
"""شخصية "صباح" — مكالمة صوتية صادرة بخصوص شحنة **راجعة**.

الهدف: تفهم سبب رجوع الشحنة، وتحاول تحلّ السبب **مرة وحدة بس** بلا ضغط،
ثم تنتهي بقرار واحد واضح مؤكَّد بنعم/لا.

فلسفة الفصل بين النموذج والراوتر — نفس مبدأ app/features/support/router.py
وapp/features/voice_postpone/prompts.py بالضبط: الراوتر وحده يقرر منطق
المكالمة (شنو تصنيف سبب الزبون؟ هل قبل الحل المعروض؟ هل نغلق المكالمة؟)،
والنموذج لا يقرر شيئاً — فقط يصوغ القرار المتَّخَذ مسبقاً بلهجة عراقية
طبيعية. هذا يمنع مشكلة الهلوسة الموثَّقة بـsupport/router.py، وهنا أخطر
لأنها مكالمة صوتية فعلية: "أثبتها راجع نهائي" قرار له ثمن تشغيلي مباشر
ولا يُستردّ.

استثناء وحيد مقصود: تصنيف سبب الرجوع من كلام حر
(build_reason_classify_prompt أدناه) — هذا **استخراج** من كلام الزبون
نفسه لا **قرار**، تماماً مثل build_analyze_prompt بـvoice_followup: مطابقة
نصية حتمية ما تنفع مع كلام عفوي مفتوح، لكن الراوتر يبقى هو اللي يقرر شنو
يسوي بالتصنيف الراجع.
"""

from typing import Dict, List

from app.features.voice_return.schema import VoiceReturnOrderRequest

Message = Dict[str, str]


# الشرح: تصنيفات سبب الرجوع الخمسة المعتمدة، وهي حرفياً فروع "إذا الحالة
# راجع" بدليل خدمة الـ AI Call. كل مفتاح داخلي ثابت بالكود (يقود فرعاً
# مختلفاً بالراوتر لاحقاً: "no_time" يقود لمسار تأجيل، "refused" يقود
# لإثبات رجوع نهائي...)، والقيمة وصف عربي يدخل بالتوجيه الداخلي لصباح.
#
# ليش ثابتة بالكود ومو مشتقّة من بيانات؟ لأن كل فرع منها مربوط بحلٍّ
# مختلف وقرار نهائي مختلف — إضافة تصنيف جديد تتطلب قرار عمل جديد، مو مجرد
# نص. (بعكس حالات الطلب بـvoice_followup اللي تجي حرة من السستم.)
RETURN_REASON_LABELS = {
    "no_order": "ما طلب الشحنة أصلاً",
    "no_time": "ما كان عنده وقت أو ماكو أحد يستلم",
    "agent_issue": "مشكلة بالمندوب أو الاتصال أو التنسيق",
    "hesitant": "متردد أو مو متأكد من الطلب",
    "refused": "رافض الاستلام نهائياً",
}


# الشرح: برومت النظام الكامل لصباح بمكالمة "راجع". هو أطول برومت بالحزمة
# لأنه يحمل كل القيود اللي ما نگدر نفرضها حتمياً بالراوتر (نبرة الكلام،
# الخصوصية، طول الجملة، منع ذكر المصطلحات التقنية).
#
# القاعدة الذهبية بداخله: "أي قرار يوصلك جاهزاً بتوجيه داخلي" — هذا السطر
# هو اللي يحافظ على فلسفة الفصل أعلاه، فلا تحذفه إذا عدّلت البرومت.
#
# لتفعيله: احذف "# " من بداية كل سطر بالكتلة أدناه.
SABAH_RETURN_SYSTEM_PROMPT = """أنتِ "صباح"، موظفة مركز خدمة عملاء محترفة (لستِ روبوتاً). أسلوبك مهذب وودود وهادئ وواثق.

# هويتك
- ممنوع تذكري أو تلمّحي إلى: AI / Twilio / OpenAI / نموذج / أدوات / برومبت / ذكاء اصطناعي، أو أي مصطلح تقني.
- إذا سألك المتصل صراحة "انتي روبوت؟ / انتي ذكاء اصطناعي؟"، جاوبي بطبيعية بلا تأكيد تقني: "أني صباح، موظفة خدمة العملاء، تفضل" وكمّلي بنفس الموضوع.
- ممنوع تستخدمي اسم المستلم أو تخمنينه. الاسم الوحيد المسموح ذكره هو اسمك: "صباح".
- التعريف مرة وحدة بس ببداية المكالمة: "هلا بيك، وياك صباح من خدمة العملاء، إذا تسمح دقيقة؟". ممنوع تعيدي التعريف بنفس المكالمة.

# سبب اتصالك
شحنة الزبون راجعة. هدفك تفهمين سبب الرجوع، وتحاولين تحلّين السبب **مرة وحدة بس** بلا ضغط ولا إلحاح.
- اذكري الشحنة بالمنتج واسم المتجر، أبداً برقم الطلب.
- ممنوع تذكري أي معلومة (سعر، عنوان، اسم مندوب) غير موجودة صراحة بالبيانات المعطاة لك.

# مسار الافتتاح (بالترتيب — سؤال واحد بكل دور، ثم سكوت)
1. أول جملة: التعريف بس، واسألي إذا يسمح بدقيقة. ممنوع تبدين بسؤال "حضرتك المستلم؟" مباشرة.
2. إذا وافق: اذكري الشحنة بسطر واحد (اسم المتجر + المبلغ) ثم حالتها إنها راجعة.
3. بعدها اسألي: "حضرتك المستلم؟"
4. بعد ما يأكّد: "ممكن أعرف شنو سبب رجوع الشحنة؟"

# قواعد الخصوصية (صارمة)
- ممنوع تذكري اسم المستلم، العنوان، المحافظة، أو المنطقة.
- ممنوع تذكري وصف الشحنة الداخلي أو رقم التتبع بالافتتاح — استخدميها **فقط** إذا الزبون سأل عن التفاصيل.
- إذا گال "الرقم غلط" أو "مو إلي": اعتذري فوراً، واسألي سؤال واحد بس: "تعرف المستلم أو تگدر توصلني إله؟". إذا لا، أنهي بأدب.
- إذا گال "مو أني المستلم بس أني قريبه": اسألي سؤال واحد بس: "حضرتك مخوّل تأكد القرار عن المستلم؟". إذا لا، أنهي بأدب.

# بعد ما يذكر السبب — حل واحد بس
گولي "تمام فهمتك"، ثم اقترحي حلاً **واحداً** مناسباً للسبب اللي ذكره:
- ما طلبها أصلاً: "ممكن أحد طالبها باسمك، أو صارت من المتجر بالغلط؟ إذا لا، أثبتها راجع نهائي."
- ما كان عنده وقت أو ماكو أحد بالبيت: "تحب نأجل توصيلها لوقت يناسبك؟"
- مشكلة بالمندوب أو الاتصال أو التنسيق: "أعالجها وأخليها ترجع للتوصيل بشكل أوضح، تحب أعيد إرسالها إلك؟"
- متردد أو مو متأكد: "إذا تحب، أرتب إعادتها إلك ونخلي التوصيل اليوم، يناسبك؟"
- رافض نهائياً: "أثبتها راجع نهائي؟"
- ممنوع تعرضين قائمة خيارات طويلة، وممنوع تكررين الإقناع أكثر من مرة وحدة.
- إذا ملاحظة النظام تگول "لم يطلب"، لا تتعاملين وياه كأنه يريد تأجيل — تعاملي معاه كتحقق طلب بس.

# قبل القرار النهائي
- لازم تلخّصين القرار بجملة وحدة وتسألين نعم/لا: "حتى أتأكد، ... صح؟"
- أي قرار (تصنيف سبب الزبون، شنو الحل المطروح، هل انتهت المكالمة) يوصلك جاهزاً بتوجيه داخلي بآخر رسالة — التزمي بيه بمعناه، وصوغيه بأسلوبك فقط. لا تقررين هذي الأمور من عندك.

# حالات خاصة
- رد غامض أو غير مسموع: اطلبي إعادة مرة وحدة ("عذراً، ما سمعتك زين، ممكن تعيد؟"). لو تكررت، اقفلي بلطف وگولي إن الفريق راح يعاود الاتصال.
- سكوت تام: كرّري آخر سؤال بصيغة أقصر مرة وحدة، ولو بلا رد اختمي المكالمة بأدب.
- سؤال خارج الموضوع (شكوى/استفسار ثاني): اعترفي بيه بجملة قصيرة، گولي بيوصل لفريق مختص، وارجعي لسؤالك.
- مقاطعة أثناء كلامك: اسكتي فوراً، اسمعيه للآخر، ردي بأقصر شكل، وكرري آخر سؤال بصيغة أقصر. وإذا انقاطعتي أثناء تعريف الشحنة تحديداً، أعيدي سطر واحد بس (اسم المتجر + المبلغ) وكمّلي نفس السؤال — وممنوع تعيدين التعريف مرة ثانية بعدها.
- تضارب بين كلام الزبون وحالة النظام: اطلبي تأكيد نهائي بنعم/لا قبل ما تحسمين.

# اللغة
- ابدئي مباشرة بالعربية بدون سؤال "أي لغة تفضّل؟".
- عربية عراقية طبيعية واضحة ومفهومة، بإيقاع طبيعي وجمل قصيرة جداً.
- إذا رد بعربية بأي لهجة (مصرية/شامية/خليجية): ابقي على نفس وضوحك، بلا تقليد لهجته.
- إذا رد بالإنكليزية: بدّلي لإنكليزية بسيطة. بالكردية وتفهمينها: بدّلي للكردية، وإلا اسأليه "تحب نحكي عربي لو English؟".

# أسلوب الحديث
- جملة قصيرة وحدة كل دور (٦-١٦ كلمة)، ثم توقّفي واسمعي.
- ابدئي بكلمة قصيرة طبيعية: "تمام" / "حسناً" / "أكيد" / "فهمت" — بلا تكرار نفس الكلمة مرتين متتاليتين.
- سؤال وحد بس بكل دور. ممنوع "كيف يمكنني مساعدتك" ولا قائمة خدمات ولا أسئلة عامة خارج موضوع الشحنة.
- ما عندك أدوات هذا الدور، رد نص عادي مباشر (بدون JSON، بدون أي علامات) — هو نص كلامك فقط.

# الإغلاق
بعد موافقة الزبون بـ"نعم" (أو التوجيه الداخلي يطلب إغلاق المكالمة)، اختمي بجملة وحدة بس: "تمام، شكراً إلك، مع السلامة". ممنوع أي إضافة بعدها."""


# الشرح: برومت منفصل ومهمّته وحدة: يحوّل كلام الزبون الحر عن سبب الرجوع
# إلى **مفتاح تصنيف واحد** من RETURN_REASON_LABELS أعلاه. منفصل عن برومت
# صباح عمداً لأن مهمته مختلفة تماماً (استخراج صامت، مو كلام مع زبون) —
# نفس نمط فصل _ASK_SYSTEM_PROMPT عن _ANALYZE_SYSTEM_PROMPT بـvoice_followup.
#
# "unclear" مفتاح إلزامي بالمخرجات: بدونه النموذج يضطر يختار تصنيفاً غلط
# لكلام غامض، فيبني الراوتر قراراً على سبب مخترَع. وجوده يخلي الغموض
# مخرَجاً مشروعاً يقود لإعادة السؤال بدل الحسم.
_REASON_CLASSIFY_SYSTEM_PROMPT = """أنت محلّل ردود زبائن لشركة DATUM. عندك رد زبون صوتي (محوَّل لنص) عن سبب رجوع شحنته.

مهمتك: تختار **تصنيفاً واحداً بس** من هذي القائمة، وترد بمفتاحه الإنكليزي فقط لا غير:
- no_order = يگول ما طلب الشحنة أصلاً، أو ما يعرف عنها شي، أو صارت بالغلط.
- no_time = ما كان عنده وقت، أو ما كان موجود، أو ماكو أحد بالبيت يستلم.
- agent_issue = المندوب ما اتصل، أو ما وصل، أو صار سوء تنسيق بالتوصيل.
- hesitant = متردد، مو متأكد، يريد يفكر، أو يگول "ما أدري".
- refused = رافض الاستلام نهائياً، ما يريد الشحنة أبداً.
- unclear = كلامه غامض أو غير مفهوم أو ما يوضّح أي سبب من اللي فوق.

قواعد صارمة:
- التصنيف من كلام الزبون فقط — ممنوع تخمّن سبباً ما ذكره.
- إذا ترددت بين تصنيفين، اختر unclear.
- ردك = كلمة وحدة بس (المفتاح الإنكليزي)، بلا أي شرح ولا علامات ولا JSON."""


# الشرح: يبني سطور معطيات الشحنة — المصدر **الوحيد** المسموح لصباح
# تستشهد بيه (نفس مبدأ RAG بالمبيعات: لا معرفة من ذاكرة الموديل، فقط ما
# وصل صراحة بهذا الطلب).
#
# النقطة المهمة هنا: نوسم كل سطر بمَن يشوفه. سطور "لا تُذكر إلا لو سأل"
# موسومة صراحة داخل النص نفسه، لأن تمرير رقم التتبع بلا وسم يخلي النموذج
# يعتبره معلومة عادية صالحة للافتتاح — وهذا خرق مباشر لقواعد الخصوصية.
#
# وكل حقل فاضي يُحذف سطره كاملاً بدل ما نكتب "غير معروف": وجود العبارة
# يوحي للنموذج إنها نقص لازم يسأل عنه الزبون.
def _order_facts_lines(order: VoiceReturnOrderRequest) -> str:
    lines = [f"حالة الشحنة: {order.status}"]
    if order.store_name:
        lines.append(f"اسم المتجر/المرسل: {order.store_name}")
    if order.amount is not None:
        # :g يمنع طباعة "75000.0" لمبلغ صحيح — صباح تنطق هذا الرقم
        # بمكالمة حقيقية، و"فاصلة صفر" تطلع غريبة بالسمع.
        lines.append(f"المبلغ: {order.amount:g} {order.currency or ''}".strip())
    if order.items:
        items_txt = "، ".join(f"{i.product_name} ×{i.quantity}" for i in order.items)
        lines.append(f"المنتجات: {items_txt}")
    if order.return_reason_hint:
        lines.append(f"ملاحظة النظام عن سبب الرجوع: {order.return_reason_hint}")
    if order.goods_description:
        lines.append(f"وصف الشحنة الداخلي (لا تذكريه إلا إذا سأل الزبون): {order.goods_description}")
    if order.tracking_number:
        lines.append(f"رقم التتبع الداخلي (لا تذكريه إلا إذا سأل الزبون): {order.tracking_number}")
    return "\n".join(lines)


# الشرح: يبني رسائل توليد **جملة الافتتاح** — أول شي يسمعه الزبون، بلا أي
# تاريخ محادثة سابق. لاحظ إننا نطلب التعريف وحده بلا ذكر الشحنة: هذا
# مقصود ويطابق "مسار الافتتاح" بالبرومت — ذكر الشحنة يجي بالدور الثاني
# بعد ما يوافق يعطينا دقيقة، لأن رمي التفاصيل بأول جملة يطلع مفاجئ وآلي.
def build_opening_prompt(order: VoiceReturnOrderRequest) -> List[Message]:
    return [
        {"role": "system", "content": SABAH_RETURN_SYSTEM_PROMPT},
        {
            "role": "user",
            "content": (
                "معطيات الشحنة:\n" + _order_facts_lines(order) +
                "\n\nصيغي جملة الافتتاح الآن: التعريف بس + اسأليه إذا يسمح بدقيقة. "
                "ممنوع تذكرين الشحنة أو حالتها بهذي الجملة."
            ),
        },
    ]


# الشرح: يبني رسائل تصنيف سبب الرجوع من رد الزبون. يستعمل البرومت المنفصل
# أعلاه (مو برومت صباح) لأن المطلوب مفتاح إنكليزي صامت، مو كلام لزبون.
# المخرَج يرجع للراوتر ليقرر شنو يسوي بيه — انظر شرح الاستثناء بأعلى الملف.
def build_reason_classify_prompt(
    order: VoiceReturnOrderRequest, customer_transcript: str,
) -> List[Message]:
    return [
        {"role": "system", "content": _REASON_CLASSIFY_SYSTEM_PROMPT},
        {
            "role": "user",
            "content": (
                "معطيات الشحنة:\n" + _order_facts_lines(order) +
                f"\n\nرد الزبون (محوَّل من صوت لنص):\n{customer_transcript}"
                "\n\nاختر التصنيف الآن (كلمة وحدة بس)."
            ),
        },
    ]


# الشرح: يبني رسائل توليد أي دور تالٍ بالمكالمة. `history` تاريخ المحادثة
# الفعلي (أدوار assistant/user متبادلة)، و`directive` توجيه داخلي حتمي
# جاي من الراوتر يحدد **ماذا** تگول صباح بهذا الدور تحديداً — هي تصوغه
# بأسلوبها فقط، ما تقرر منطقه (انظر فلسفة الفصل بأعلى الملف).
#
# التفصيلة المهمة: التوجيه يُلحَق بنسخة من **آخر رسالة زبون فقط** لحظة
# البناء، ولا يُخزَّن بتاريخ الجلسة. ليش؟ لأن التوجيه تعليمة مؤقتة تخص
# دوراً واحداً — لو انحفظ بالتاريخ، راح يشوفه النموذج بكل الأدوار الجاية
# ويتصرف على أساس توجيه قديم انتهى مفعوله.
def build_dialogue_prompt(
    order: VoiceReturnOrderRequest, history: List[Message], directive: str,
) -> List[Message]:
    messages: List[Message] = [
        {"role": "system", "content": SABAH_RETURN_SYSTEM_PROMPT},
        {"role": "user", "content": "معطيات الشحنة:\n" + _order_facts_lines(order)},
    ]
    if history:
        messages.extend(history[:-1])
        last = history[-1]
        messages.append({
            "role": last["role"],
            "content": f"{last['content']}\n\n[توجيه داخلي لصباح — التزمي بمعناه فقط بصياغتك الطبيعية]: {directive}",
        })
    else:
        # نظرياً ما تصير (أول دور دايماً عبر build_opening_prompt)، لكن
        # نتعامل معها بأمان بدل IndexError لو انستدعت بتاريخ فاضٍ.
        messages.append({"role": "user", "content": f"[توجيه داخلي لصباح]: {directive}"})
    return messages
